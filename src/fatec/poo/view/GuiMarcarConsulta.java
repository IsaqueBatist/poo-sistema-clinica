    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        int codigoConsulta = 0;
        try {
            codigoConsulta = Integer.parseInt(this.txtCodigo.getText());
        } catch (NumberFormatException nfe) {
            this.exibirMensagemErro("Erro! é necessário fornecer o código da consulta");
        }

        consulta = this.daoConsulta.consultar(codigoConsulta);

        paciente = null;

        btnConsultar.setEnabled(false);
        if (consulta == null) {
            txtCodigo.setEnabled(false);
            this.ftxtCpfMedico.setEnabled(true);
            this.ftxtCpfPaciente.setEnabled(true);
            this.ftxtData.setEnabled(true);
            this.ftxtValor.setEnabled(true);

            btnInserir.setEnabled(true);
            btnConsultarMedico.setEnabled(true);
            btnConsultarPaciente.setEnabled(true);

            ftxtCpfMedico.requestFocus();
        } else {
            txtCodigo.setText(String.valueOf(consulta.getCodigo()));
            ftxtCpfMedico.setText(consulta.getMedico().getCpf());
            lblNomeMedico.setText(consulta.getMedico().getNome());

            String cpfDoPaciente = daoConsulta.consultarCpfDePacientePorCodigoConsulta(codigoConsulta);

            paciente = daoPaciente.consultar(cpfDoPaciente);

            ftxtCpfPaciente.setText(paciente.getCpf());
            lblNomePaciente.setText(paciente.getNome());
            ftxtData.setText(consulta.getData());
            ftxtValor.setText(String.valueOf(consulta.getValor()));

            btnAlterar.setEnabled(true);
            btnExcluir.setEnabled(true);

            txtCodigo.setEnabled(false);
            ftxtData.setEnabled(true);
            ftxtValor.setEnabled(true);

            ftxtData.requestFocus();
        }
    }//GEN-LAST:event_btnConsultarActionPerformed

