    private void btnInserirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInserirActionPerformed
        if (!isValidoTodosOsCamposObrigatorios()) {
            return;
        }

        consulta = new Consulta(Integer.parseInt(txtCodigo.getText()), ftxtData.getText());

        try {
            consulta.setValor(formatarValor());
        } catch (NumberFormatException e) {
            exibirMensagemErro("O valor do campo 'valor' tem que ser um número!");
            return;
        }

        consulta.setMedico(medico);

        daoConsulta.inserir(consulta, paciente);

        limpar();
    }//GEN-LAST:event_btnInserirActionPerformed

    private void btnConsultarMedicoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarMedicoActionPerformed
        medico = null;

        String cpfSemPontuacao = formatarCpf(ftxtCpfMedico.getText().trim());

        if (!Pessoa.validarCPF(cpfSemPontuacao)) {
            exibirMensagemErro("CPF de médico inválido");
            return;
        }

        medico = daoMedico.consultar(cpfSemPontuacao);

        if (medico == null) {
            exibirMensagemErro("Médico não cadastrado!");
            return;
        }

        lblNomeMedico.setText(medico.getNome());

        ftxtCpfMedico.setEnabled(false);
        btnConsultarMedico.setEnabled(false);

        ftxtCpfPaciente.requestFocus();
    }//GEN-LAST:event_btnConsultarMedicoActionPerformed

