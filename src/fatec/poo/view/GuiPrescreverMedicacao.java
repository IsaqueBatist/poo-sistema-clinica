    private void btnConsultarCodigoConsultaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarCodigoConsultaActionPerformed
        String codigoConsulta = this.txtCodigoConsulta.getText();
        try {
            Integer.parseInt(codigoConsulta);
        } catch (NumberFormatException nfe) {
            this.exibirMensagemErro("O campo 'Código Consulta' deve ser um número.");
            return;
        }
        
        
        if(codigoConsulta.isEmpty()){
            this.exibirMensagemErro("O campo 'Código Consulta' não pode ficar vazio.");
            return;
        }
        
        consulta = this.daoConsulta.consultar(Integer.parseInt(codigoConsulta));
        
        if(consulta == null){
            this.exibirMensagemErro("Consulta não encontrada");
            return;
        }
        
        
        this.lblNomeMedico.setText(consulta.getMedico().getNome());;
        this.habilitarCriar();
    }//GEN-LAST:event_btnConsultarCodigoConsultaActionPerformed

