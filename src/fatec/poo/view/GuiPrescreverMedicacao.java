    private boolean isCampoObrigatorioValido(JTextField campo, String nomeCampo) {

        String textoDoCampo = campo.getText().trim();

        if (textoDoCampo.isEmpty()) {
            JOptionPane.showMessageDialog(
                    null,
                    "O campo " + nomeCampo + " é obrigatório! Por favor, preencha-o.",
                    "Campo obrigatório",
                    JOptionPane.ERROR_MESSAGE
            );

            campo.requestFocus();

            return false;
        }
        return true;
    }

    private boolean isValidoTodosOsCamposObrigatorios() {
        return (isCampoObrigatorioValido(txtNome, "Nome")
                && isCampoObrigatorioValido(txtCodigoConsulta, "Código Consulta")
                && isCampoObrigatorioValido(txtDosagem, "Dosagem")
                && isCampoObrigatorioValido(txtQuantidadeDias, "Quantidade Dias"));
    }
    
    private void habilitarCampoConsulta(){
        this.txtCodigoConsulta.setEnabled(true);
        this.btnConsultarCodigoConsulta.setEnabled(true);
    }
    
    private void habilitarCriar(){
        this.txtCodigoConsulta.setEnabled(false);
        this.btnConsultarCodigoConsulta.setEnabled(false);
        this.btnConsultar.setEnabled(false);
        
        
        this.txtDosagem.setEnabled(true);
        this.txtQuantidadeDias.setEnabled(true);   
    
        this.btnInserir.setEnabled(true);
    }
    
    private void habilitarAtualizar(){
        this.txtCodigoConsulta.setEnabled(false);
        this.btnConsultarCodigoConsulta.setEnabled(false);
        this.btnConsultar.setEnabled(false);
        
        
        this.txtDosagem.setEnabled(true);
        this.txtQuantidadeDias.setEnabled(true);   
    
        this.btnAlterar.setEnabled(true);
        this.btnExcluir.setEnabled(true);
    }
    
    private void pegarValoresFormulario(){
        this.medicacao.setDosagem(this.txtDosagem.getText());
        this.medicacao.setQtdeDias(Integer.parseInt(this.txtQuantidadeDias.getText()));
    }
    
    private void preencherFormulario(){
        this.txtNome.setText(this.medicacao.getNome());
        this.txtDosagem.setText(this.medicacao.getDosagem());
        this.txtQuantidadeDias.setText(String.valueOf(this.medicacao.getQtdeDias()));
    }
    
    private void resetarFormulario(){
        this.txtNome.setText("");
        this.txtCodigoConsulta.setText("");
        this.txtDosagem.setText("");
        this.txtQuantidadeDias.setText("");
        this.lblNomeMedico.setText("");
        
        this.txtNome.setEnabled(true);
        this.txtCodigoConsulta.setEnabled(false);
        this.txtDosagem.setEnabled(false);
        this.txtQuantidadeDias.setEnabled(false);
        
        this.btnAlterar.setEnabled(false);
        this.btnConsultar.setEnabled(true);
        this.btnConsultarCodigoConsulta.setEnabled(false);
        this.btnExcluir.setEnabled(false);
        this.btnInserir.setEnabled(false);
    }
