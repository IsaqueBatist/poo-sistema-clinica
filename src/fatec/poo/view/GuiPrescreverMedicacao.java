    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        String nomeMedicacao = this.txtNome.getText();
        if(nomeMedicacao.isEmpty()){
            this.exibirMensagemErro("O campo 'nome' não pode ficar vazio.");
            return;
        }
        
        medicacao = this.daoMedicacao.consultar(nomeMedicacao);
        if(medicacao == null){
            this.habilitarCampoConsulta();
        }else {
            Integer codigoConsulta = daoMedicacao.consultarConsultaPorNome(nomeMedicacao);
            consulta = daoConsulta.consultar(codigoConsulta);
            this.txtCodigoConsulta.setText(String.valueOf(consulta.getCodigo()));
            this.lblNomeMedico.setText(consulta.getMedico().getNome());
            this.preencherFormulario();
            this.habilitarAtualizar();
        }
        
        
        this.txtNome.setEnabled(false);
        this.txtDosagem.requestFocus();
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnInserirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInserirActionPerformed
        if(!this.isValidoTodosOsCamposObrigatorios()){
            return;
        }
        
        this.medicacao = new Medicacao(this.txtNome.getText());
        
        this.pegarValoresFormulario();
        
        this.daoMedicacao.inserir(medicacao, consulta.getCodigo());
        
        this.resetarFormulario();
        
    }//GEN-LAST:event_btnInserirActionPerformed

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        if(!this.isValidoTodosOsCamposObrigatorios()){
            return;
        }
        if(JOptionPane.showConfirmDialog(null, "Confirma Alteração?") == 0){
            this.pegarValoresFormulario();
            this.daoMedicacao.alterar(medicacao);
            this.resetarFormulario();
        }
    }//GEN-LAST:event_btnAlterarActionPerformed

